#!/usr/bin/env node
/**
 * GTK4 CSS to Browser CSS Converter
 *
 * Converts GTK4-specific CSS syntax to browser-compatible CSS.
 * Used to sync effects.css from the theme to the docs demo.
 *
 * Handles:
 * - alpha(@color_name, opacity) -> rgba(r, g, b, opacity)
 * - alpha(currentColor, opacity) -> rgba(255, 255, 255, opacity)
 * - @color_name references in other contexts
 */

const fs = require('fs');
const path = require('path');

// GTK4/Adwaita color mappings to browser hex values
const COLOR_MAP = {
  // Error/danger colors
  '@error_color': { r: 231, g: 76, b: 60 },    // #e74c3c

  // Warning colors
  '@warning_color': { r: 241, g: 196, b: 15 }, // #f1c40f

  // Success colors
  '@success_color': { r: 46, g: 204, b: 113 }, // #2ecc71

  // Accent/primary colors
  '@accent_color': { r: 52, g: 152, b: 219 },  // #3498db
  '@accent_bg_color': { r: 52, g: 152, b: 219 },

  // Window colors (dark theme approximation)
  '@window_fg_color': { r: 255, g: 255, b: 255 },
  '@window_bg_color': { r: 36, g: 36, b: 36 },

  // Fallback for currentColor (white for dark theme)
  'currentColor': { r: 255, g: 255, b: 255 },

  // Basic named colors used in GTK4 CSS
  'black': { r: 0, g: 0, b: 0 },
  'white': { r: 255, g: 255, b: 255 },
};

/**
 * Convert alpha(@color, opacity) to rgba(r, g, b, opacity)
 */
function convertAlphaFunction(css) {
  // Match: alpha(@variable, 0.5) or alpha(currentColor, 0.5) or alpha(black, 0.5)
  const alphaRegex = /alpha\(\s*(@[\w_]+|currentColor|black|white)\s*,\s*([\d.]+)\s*\)/g;

  return css.replace(alphaRegex, (match, colorRef, opacity) => {
    const color = COLOR_MAP[colorRef];
    if (color) {
      return `rgba(${color.r}, ${color.g}, ${color.b}, ${opacity})`;
    }
    // Unknown color - use white as fallback
    console.warn(`Unknown color reference: ${colorRef}, using white`);
    return `rgba(255, 255, 255, ${opacity})`;
  });
}

/**
 * Convert standalone @color references to hex
 */
function convertColorReferences(css) {
  // Match standalone @variable (not inside alpha())
  // This is tricky - we need to not match inside alpha() calls
  // For now, just handle simple cases like: color: @error_color;
  const colorRefRegex = /:\s*(@[\w_]+)\s*;/g;

  return css.replace(colorRefRegex, (match, colorRef) => {
    const color = COLOR_MAP[colorRef];
    if (color) {
      const hex = `#${color.r.toString(16).padStart(2, '0')}${color.g.toString(16).padStart(2, '0')}${color.b.toString(16).padStart(2, '0')}`;
      return `: ${hex};`;
    }
    return match;
  });
}

/**
 * Add header comment
 */
function addHeader(css, sourcePath) {
  const header = `/**
 * AUTO-GENERATED - DO NOT EDIT
 *
 * This file is automatically generated from:
 *   ${sourcePath}
 *
 * To modify effects, edit the source file and run:
 *   npm run generate:effects
 *
 * Generated: ${new Date().toISOString()}
 */

`;
  return header + css;
}

/**
 * Main conversion function
 */
function convertGtkCss(inputPath, outputPath) {
  console.log(`Converting: ${inputPath}`);
  console.log(`Output: ${outputPath}`);

  // Read source file
  let css;
  try {
    css = fs.readFileSync(inputPath, 'utf8');
  } catch (err) {
    console.error(`Error reading ${inputPath}:`, err.message);
    process.exit(1);
  }

  // Apply conversions
  css = convertAlphaFunction(css);
  css = convertColorReferences(css);

  // Add header
  const relativePath = path.relative(path.dirname(outputPath), inputPath);
  css = addHeader(css, relativePath);

  // Ensure output directory exists
  const outputDir = path.dirname(outputPath);
  if (!fs.existsSync(outputDir)) {
    fs.mkdirSync(outputDir, { recursive: true });
  }

  // Write output
  try {
    fs.writeFileSync(outputPath, css);
    console.log('Conversion complete!');
  } catch (err) {
    console.error(`Error writing ${outputPath}:`, err.message);
    process.exit(1);
  }
}

// CLI usage
if (require.main === module) {
  const args = process.argv.slice(2);

  if (args.length === 0) {
    // Default: convert effects.css for docs
    const repoRoot = path.resolve(__dirname, '../..');
    const inputPath = path.join(repoRoot, 'embed/themes/effects.css');
    const outputPath = path.join(__dirname, '../src/components/AnimationDemo/effects-generated.css');

    convertGtkCss(inputPath, outputPath);
  } else if (args.length === 2) {
    convertGtkCss(args[0], args[1]);
  } else {
    console.log('Usage: convert-gtk-css.js [input.css output.css]');
    console.log('       convert-gtk-css.js  (uses default paths)');
    process.exit(1);
  }
}

module.exports = { convertGtkCss, convertAlphaFunction, convertColorReferences };
